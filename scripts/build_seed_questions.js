function getDomain(id) {
  if (id <= 9) return 'executing';
  if (id <= 17) return 'influencing';
  if (id <= 26) return 'relationship';
  return 'strategic';
}

function buildGraph() {
  const talents = Array.from({ length: 34 }, (_, i) => i + 1);
  for (let attempt = 0; attempt < 5000; attempt++) {
    const degrees = {};
    talents.forEach(t => degrees[t] = 0);
    const edges = [];
    const edgeSet = new Set();
    const shuffle = arr => [...arr].sort(() => Math.random() - 0.5);
    
    for (let round = 0; round < 4; round++) {
      const order = shuffle(talents).sort((a, b) => degrees[a] - degrees[b]);
      for (const u of order) {
        if (degrees[u] >= 4) continue;
        const uDom = getDomain(u);
        const candidates = shuffle(talents).filter(v => 
          v !== u && 
          degrees[v] < 4 && 
          getDomain(v) !== uDom &&
          !edgeSet.has(`${Math.min(u, v)}-${Math.max(u, v)}`)
        ).sort((a, b) => degrees[a] - degrees[b]);
        
        if (candidates.length > 0) {
          const v = candidates[0];
          edges.push([u, v]);
          edgeSet.add(`${Math.min(u, v)}-${Math.max(u, v)}`);
          degrees[u]++;
          degrees[v]++;
        }
      }
    }
    
    if (edges.length === 68 && talents.every(t => degrees[t] === 4)) {
      return edges;
    }
  }
  throw new Error("Graph construction failed");
}

const edges = buildGraph();

// Now assign statements to each usage of talent
const usageCount = {};
for (let i = 1; i <= 34; i++) usageCount[i] = 0;

const questions = edges.map((pair, index) => {
  const [tA, tB] = Math.random() > 0.5 ? [pair[0], pair[1]] : [pair[1], pair[0]];
  const stmtA = STATEMENTS[tA][usageCount[tA]++];
  const stmtB = STATEMENTS[tB][usageCount[tB]++];
  
  return {
    orderIndex: index + 1,
    talentAId: tA,
    statementA: stmtA,
    talentBId: tB,
    statementB: stmtB
  };
});

// Verification assertions:
console.log("Total questions:", questions.length);
const countT = {};
for (let i = 1; i <= 34; i++) countT[i] = 0;
let crossDomainValid = true;

questions.forEach(q => {
  countT[q.talentAId]++;
  countT[q.talentBId]++;
  if (getDomain(q.talentAId) === getDomain(q.talentBId)) crossDomainValid = false;
  if (!q.statementA || !q.statementB) throw new Error("Missing statement!");
});

for (let i = 1; i <= 34; i++) {
  if (countT[i] !== 4) throw new Error(`Talent ${i} count is ${countT[i]}, expected 4`);
}
if (!crossDomainValid) throw new Error("Intra-domain pairing found!");
console.log("All verifications passed! All 34 talents appear exactly 4 times, 100% cross-domain.");

